"""
Alembic ``render_item`` hook: render the app's custom column types as plain SQLAlchemy ones.

`UTCDateTime` is a `TypeDecorator` over ``DateTime(timezone=True)`` (same column, no schema
change). Without this hook an autogenerated migration would reference ``UTCDateTime`` and fail
to import it; a migration must not depend on application code that may change later.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Literal

from your_service_name.backend.db.models import UTCDateTime

if TYPE_CHECKING:
    from alembic.autogenerate.api import AutogenContext


def render_item(
    type_: str,
    obj: Any,  # noqa: ANN401
    _autogen_context: AutogenContext | None,
) -> str | Literal[False]:
    """Return the code for ``UTCDateTime`` types; ``False`` leaves the default rendering."""
    if type_ == "type" and isinstance(obj, UTCDateTime):
        return "sa.DateTime(timezone=True)"
    return False
